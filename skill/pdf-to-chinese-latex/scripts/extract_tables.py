# -*- coding: utf-8 -*-
"""Extract tabular data from a PDF as ready-to-paste LaTeX tabularx blocks.

Stats / econometrics / energy papers often carry the bulk of their results
in tables, not figures. Hand-rebuilding a 20-row regression table in
LaTeX takes ~30 minutes and is error-prone. This script asks pdfplumber
to detect tables page-by-page, then for each table emits:

    \\begin{table}[!htbp]
    \\centering
    \\caption{TODO}
    \\label{tab:p<page>-t<idx>}
    \\begin{tabular}{lrrrr...}
        \\toprule
        col1 & col2 & col3 & ... \\\\
        \\midrule
        row1 cells joined with &  \\\\
        ...
        \\bottomrule
    \\end{tabular}
    \\end{table}

The translator pastes the block into main.tex, fills in caption + label,
and tweaks column types as needed. The sidecar file is `_tables.tex` next
to `main.tex` — same paste-ready pattern as `_figure_includes.tex`.

Usage:
    python extract_tables.py input.pdf --out output_dir/_tables.tex
    python extract_tables.py input.pdf                 # writes to stdout
    python extract_tables.py input.pdf --pages 4,5,6   # restrict to pages

Requires: pdfplumber (`pip install pdfplumber`).
"""
import argparse
import io
import os
import re
import sys
from typing import List, Optional

import pdfplumber


def _latex_escape(s: str) -> str:
    """Escape characters that would break a LaTeX tabularx cell.
    Conservative — keeps the text readable for translator review."""
    if s is None:
        return ""
    s = str(s)
    out = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\":
            out.append("\\textbackslash{}")
        elif c in "&_%#$":
            out.append("\\" + c)
        elif c in "{}":
            out.append("\\" + c)
        elif c == "~":
            out.append("\\textasciitilde{}")
        elif c == "^":
            out.append("\\textasciicircum{}")
        else:
            out.append(c)
        i += 1
    return "".join(out)


def _column_spec(rows: List[List[str]]) -> str:
    """Heuristic column spec: first column left-aligned (labels), rest
    right-aligned (likely numbers). Header row excluded from analysis."""
    if not rows:
        return "l"
    ncols = max(len(r) for r in rows)
    body = rows[1:] if len(rows) > 1 else rows
    spec = ["l"]  # first col label
    for c in range(1, ncols):
        # check if values in column c look numeric (digits / sign / decimal / parens for negatives)
        numericness = 0
        total = 0
        for r in body:
            if c < len(r):
                cell = (r[c] or "").strip()
                if not cell:
                    continue
                total += 1
                if re.match(r"^[\(\-\+]?\d[\d,.\s\-eE+]*[\)\*]?$", cell):
                    numericness += 1
        spec.append("r" if total and numericness / total >= 0.6 else "l")
    return "".join(spec)


def _emit_table_block(rows: List[List[str]], page_num: int, tab_idx: int) -> str:
    """Build a paste-ready table block from extracted rows."""
    if not rows or not rows[0]:
        return ""
    ncols = max(len(r) for r in rows)
    # Normalize: pad short rows with empty cells.
    rows = [r + [""] * (ncols - len(r)) for r in rows]
    # Drop entirely empty rows
    rows = [r for r in rows if any((c or "").strip() for c in r)]
    if not rows:
        return ""

    spec = _column_spec(rows)
    header = rows[0]
    body = rows[1:]
    use_booktabs = True

    lines = [
        f"% --- page {page_num}, table {tab_idx + 1} ({ncols} cols x {len(rows)} rows) ---",
        "\\begin{table}[!htbp]",
        "\\centering",
        "\\caption{TODO}",
        f"\\label{{tab:p{page_num}-t{tab_idx + 1}}}",
        f"\\begin{{tabular}}{{{spec}}}",
    ]
    if use_booktabs:
        lines.append("\\toprule")
    lines.append(" & ".join(_latex_escape(c) for c in header) + " \\\\")
    lines.append("\\midrule" if use_booktabs else "\\hline")
    for r in body:
        lines.append(" & ".join(_latex_escape(c) for c in r) + " \\\\")
    lines.append("\\bottomrule" if use_booktabs else "\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    return "\n".join(lines)


def extract(
    pdf_path: str,
    page_filter: Optional[List[int]] = None,
) -> str:
    """Return all tables in the PDF as a concatenated LaTeX string."""
    out = io.StringIO()
    out.write("% ============================================================\n")
    out.write("% Auto-generated by extract_tables.py\n")
    out.write("% Each table block is paste-ready: fill in \\caption{...} and\n")
    out.write("% adjust column types (l/c/r/p{...}) as needed. booktabs is\n")
    out.write("% used (loaded by latex_template.tex by default).\n")
    out.write("% ============================================================\n\n")
    total_tables = 0
    with pdfplumber.open(pdf_path) as pdf:
        for page_idx, page in enumerate(pdf.pages, 1):
            if page_filter and page_idx not in page_filter:
                continue
            # pdfplumber's default 'lines' strategy needs literal table
            # borders, which booktabs-style academic tables don't have
            # (top/middle/bottom rules only). Fall back to text-position
            # clustering when the line-based pass finds nothing — covers
            # most stats / econ papers.
            tables: List[List[List[str]]] = []
            try:
                tables = page.extract_tables() or []
            except Exception as e:
                sys.stderr.write(
                    f"  [warn] extract_tables (lines) on page {page_idx}: {e}\n"
                )
            if not tables:
                try:
                    tables = page.extract_tables(table_settings={
                        "vertical_strategy": "text",
                        "horizontal_strategy": "text",
                        "snap_tolerance": 4,
                    }) or []
                except Exception as e:
                    sys.stderr.write(
                        f"  [warn] extract_tables (text) on page {page_idx}: {e}\n"
                    )
                    continue
            for tab_idx, rows in enumerate(tables):
                # Filter tiny extractions (likely false positives)
                if not rows or len(rows) < 2:
                    continue
                ncols = max(len(r) for r in rows)
                if ncols < 2:
                    continue
                block = _emit_table_block(rows, page_idx, tab_idx)
                if block:
                    out.write(block)
                    out.write("\n")
                    total_tables += 1
    out.write(f"\n% Total: {total_tables} table(s) extracted\n")
    return out.getvalue(), total_tables


def _parse_pages(spec: str) -> List[int]:
    """Parse `1,3,5-7,10` style page filter."""
    out: List[int] = []
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            out.extend(range(int(a), int(b) + 1))
        else:
            out.append(int(part))
    return sorted(set(out))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("pdf", help="path to the input PDF")
    parser.add_argument(
        "--out", default=None,
        help="output .tex path (default writes to stdout)",
    )
    parser.add_argument(
        "--pages", default=None,
        help="restrict to pages, e.g. `4,5,7-9`",
    )
    args = parser.parse_args()

    if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

    if not os.path.isfile(args.pdf):
        sys.stderr.write(f"ERROR: {args.pdf}: file not found\n")
        sys.exit(2)

    page_filter = _parse_pages(args.pages) if args.pages else None
    block, n_tables = extract(args.pdf, page_filter)

    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(block)
        sys.stderr.write(f"Wrote {n_tables} table(s) → {args.out}\n")
    else:
        sys.stdout.write(block)

    # Exit 1 if no tables found — helpful in CI / batch contexts to know
    # immediately that this PDF has nothing to extract.
    sys.exit(0 if n_tables > 0 else 1)


if __name__ == "__main__":
    main()
